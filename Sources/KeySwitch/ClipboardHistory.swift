import AppKit

/// The last few copied texts, in memory only (never written to disk), shown in the menu bar panel.
final class ClipboardHistory {
    struct Entry: Identifiable, Hashable {
        let id = UUID()
        let text: String
        let date: Date
        let app: String
    }

    static let limit = 5
    private(set) var items: [Entry] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Password managers mark secrets with these types; we never record them.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    /// While we copy a word ourselves (right ⌥ in a field without Accessibility) and put your clipboard back.
    nonisolated(unsafe) static var pausedUntil = Date.distantPast

    private func poll() {
        if Date() < Self.pausedUntil {
            lastChange = NSPasteboard.general.changeCount
            return
        }
        guard Settings.shared.clipboardEnabled else {
            if !items.isEmpty { items = [] }
            lastChange = NSPasteboard.general.changeCount
            return
        }
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }
        guard let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.count < 100_000 else { return }
        add(s, app: NSWorkspace.shared.frontmostApplication?.localizedName ?? "—")
    }

    func add(_ s: String, app: String) {
        items.removeAll { $0.text == s }
        items.insert(Entry(text: s, date: Date(), app: app), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    func clear() { items = [] }

    /// Puts text on the clipboard without recording it again as "new".
    func write(_ s: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(s, forType: .string)
        lastChange = pb.changeCount
        add(s, app: "KeySwitch")
    }
}

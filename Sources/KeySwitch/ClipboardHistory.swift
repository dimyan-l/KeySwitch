import AppKit

/// Small clipboard manager: last N text copies in memory (never written to disk) + pinned snippets
/// that persist (handy for standard phrases, links, signatures).
final class ClipboardHistory {
    private(set) var items: [String] = []
    private let store: UserStore
    private let pasteboard: NSPasteboard
    private let foregroundBundleIdentifier: () -> String?
    private let recordingEnabled: () -> Bool
    private let workspaceNotifications: NotificationCenter
    private var lastChange: Int
    private var suspendedUntil = Date.distantPast
    private var timer: Timer?
    private var activationObserver: NSObjectProtocol?

    /// Password managers mark secrets with these types; we never record them.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
    private let sensitiveApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7",
        "com.apple.keychainaccess", "com.bitwarden.desktop", "org.keepassxc.keepassxc",
    ]

    init(store: UserStore, pasteboard: NSPasteboard = .general,
         recordingEnabled: @escaping () -> Bool = { Settings.shared.clipboardEnabled },
         foregroundBundleIdentifier: @escaping () -> String? = {
             NSWorkspace.shared.frontmostApplication?.bundleIdentifier
         }, workspaceNotifications: NotificationCenter = NSWorkspace.shared.notificationCenter) {
        self.store = store
        self.recordingEnabled = recordingEnabled
        self.pasteboard = pasteboard
        self.foregroundBundleIdentifier = foregroundBundleIdentifier
        self.workspaceNotifications = workspaceNotifications
        self.lastChange = pasteboard.changeCount
    }

    var pinned: [String] { store.pinned }

    deinit {
        timer?.invalidate()
        if let activationObserver { workspaceNotifications.removeObserver(activationObserver) }
    }

    func start() {
        guard timer == nil else { return }
        // A poll cannot attribute a pending copy after focus has changed. Discard it
        // at the workspace boundary, even if the new foreground app is not sensitive.
        activationObserver = workspaceNotifications.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: nil
        ) { [weak self] _ in
            guard let self else { return }
            self.lastChange = self.pasteboard.changeCount
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    /// Our own copy/paste tricks (selection fixes) should not pollute the history.
    func suspend(for seconds: TimeInterval) {
        suspendedUntil = Date().addingTimeInterval(seconds)
    }

    func poll() {
        let pb = pasteboard
        guard recordingEnabled() else {
            items.removeAll()
            lastChange = pb.changeCount
            return
        }
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Date() > suspendedUntil else { return }
        if let source = foregroundBundleIdentifier()?.lowercased(),
           sensitiveApps.contains(source) { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }
        guard let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.count < 100_000 else { return }
        add(s)
    }

    private func add(_ s: String) {
        items.removeAll { $0 == s }
        items.insert(s, at: 0)
        let limit = Settings.shared.clipboardSize
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func togglePin(_ s: String) {
        var p = store.pinned
        if let i = p.firstIndex(of: s) { p.remove(at: i) } else { p.insert(s, at: 0) }
        store.pinned = p
    }

    func clear() { items = [] }

    /// Puts text on the clipboard without recording it again as "new".
    func write(_ s: String) {
        let pb = pasteboard
        pb.clearContents()
        pb.setString(s, forType: .string)
        lastChange = pb.changeCount
        if recordingEnabled() { add(s) } else { items.removeAll() }
    }

    // MARK: - Save / restore the whole clipboard (for selection tricks)

    typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    func snapshot() -> Snapshot? {
        let source = pasteboard.pasteboardItems ?? []
        guard source.count <= 8 else { return nil }
        let largeTypes: Set<String> = ["public.tiff", "public.png", "public.jpeg", "com.adobe.pdf", "public.file-url"]
        var totalBytes = 0
        var result: Snapshot = []
        for item in source {
            guard Set(item.types.map(\.rawValue)).isDisjoint(with: largeTypes) else { return nil }
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types {
                if let data = item.data(forType: t) {
                    totalBytes += data.count
                    guard totalBytes <= 2 * 1024 * 1024 else { return nil }
                    d[t] = data
                }
            }
            result.append(d)
        }
        return result
    }

    func restore(_ snap: Snapshot) {
        let pb = pasteboard
        pb.clearContents()
        let items: [NSPasteboardItem] = snap.map { dict in
            let item = NSPasteboardItem()
            for (t, data) in dict { item.setData(data, forType: t) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
        lastChange = pb.changeCount
    }

    // MARK: - Menu

    static func title(for s: String) -> String {
        let oneLine = s.replacingOccurrences(of: "\n", with: " ⏎ ").trimmingCharacters(in: .whitespaces)
        return oneLine.count > 60 ? String(oneLine.prefix(57)) + "…" : oneLine
    }

    /// Click = paste. ⌥+click = pin / unpin. Digits 1–9 = quick paste.
    func buildItems(target: AnyObject, paste: Selector, pin: Selector) -> [NSMenuItem] {
        var result: [NSMenuItem] = []
        func make(_ s: String, index: Int?, pinnedItem: Bool) {
            let key = index.map { $0 < 9 ? String($0 + 1) : "" } ?? ""
            let item = NSMenuItem(title: (pinnedItem ? "📌 " : "") + Self.title(for: s), action: paste, keyEquivalent: key)
            item.keyEquivalentModifierMask = []
            item.target = target
            item.representedObject = s
            item.toolTip = String(s.prefix(500))
            result.append(item)
            let alt = NSMenuItem(title: (pinnedItem ? "Открепить: " : "Закрепить: ") + Self.title(for: s), action: pin, keyEquivalent: key)
            alt.keyEquivalentModifierMask = [.option]
            alt.isAlternate = true
            alt.target = target
            alt.representedObject = s
            result.append(alt)
        }
        if !pinned.isEmpty {
            result.append(Self.header("Закреплённые"))
            for s in pinned { make(s, index: nil, pinnedItem: true) }
            result.append(.separator())
        }
        result.append(Self.header(items.isEmpty ? "История пуста" : "История (⌥ — закрепить)"))
        for (i, s) in items.enumerated() { make(s, index: i, pinnedItem: false) }
        return result
    }

    static func header(_ title: String) -> NSMenuItem {
        let item = NSMenuItem(title: title, action: nil, keyEquivalent: "")
        item.isEnabled = false
        return item
    }
}
